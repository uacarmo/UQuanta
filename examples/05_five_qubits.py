from quantum import QuantumRegister


print("--- 5 Qubit Computer ---")

qc = QuantumRegister(5)


# ------------------------------------------------------------
# Qubit 0
# ------------------------------------------------------------

qc.h(0)


# ------------------------------------------------------------
# Entangle qubits 0 and 1
# ------------------------------------------------------------

qc.cnot(0, 1)


# ------------------------------------------------------------
# Qubit 2
# ------------------------------------------------------------

qc.h(2)


# ------------------------------------------------------------
# Entangle qubits 2 and 3
# ------------------------------------------------------------

qc.cnot(2, 3)


# ------------------------------------------------------------
# Rotate qubit 4
# ------------------------------------------------------------

qc.ry(
    theta=0.5,
    target=4
)


# ------------------------------------------------------------
# Display state
# ------------------------------------------------------------

print("\nProbabilities:")

qc.print_probabilities()


# ------------------------------------------------------------
# Measurement
# ------------------------------------------------------------

print("\nMeasurement:")

print(
    qc.measure(shots=1000)
)


# ------------------------------------------------------------
# Bloch vector
# ------------------------------------------------------------

print("\nBloch vector of qubit 0:")

print(
    qc.bloch_vector(0)
)